"""Personalise a generated offline BCD hive; no registry/firmware access.

The fixed-size device records are qualified GPT partition descriptors. The
template is generated by build_bcd_template.py using Microsoft's Offreg API,
not copied from a machine's boot store. No host identifiers are embedded.
"""
import hashlib
import struct
import uuid

BOOTMGR = '{9dea862c-5cdd-4e70-acc1-f32b344d4795}'
LOADER = '{7c10d1ea-8239-4bc7-8234-efdb85bc913a}'
PLACEHOLDER_DISK = '22222222-aaaa-4bbb-8ccc-222222222222'
PLACEHOLDER_ESP = '33333333-aaaa-4bbb-8ccc-333333333333'
PLACEHOLDER_WINDOWS = '44444444-aaaa-4bbb-8ccc-444444444444'


def device_blob(disk_guid, partition_guid):
    return (bytes(16) + struct.pack('<IIII', 6, 0, 72, 0)
            + uuid.UUID(partition_guid).bytes_le + bytes(8)
            + uuid.UUID(disk_guid).bytes_le + bytes(16))


def personalise(template, expected_sha256, disk_guid, esp_guid, windows_guid):
    if len({uuid.UUID(x) for x in (disk_guid, esp_guid, windows_guid)}) != 3:
        raise ValueError('Disk and partition GUIDs must be distinct')
    return _personalise(template, expected_sha256, disk_guid, esp_guid, windows_guid)


def personalise_colocated(template, expected_sha256, disk_guid, windows_guid):
    """Separate boot store on the SAME NTFS partition as its Windows install.

    Explicit API, not a relaxation of the earlier separate-ESP Win7 contract.
    Firmware must load this store's boot manager from this partition's device.
    """
    if uuid.UUID(disk_guid) == uuid.UUID(windows_guid):
        raise ValueError('Disk and Windows partition GUIDs must differ')
    return _personalise(template, expected_sha256, disk_guid, windows_guid, windows_guid)


def _personalise(template, expected_sha256, disk_guid, esp_guid, windows_guid):
    if hashlib.sha256(template).hexdigest() != expected_sha256:
        raise ValueError('BCD template hash mismatch')
    if template[:4] != b'regf' or len(template) < 4096:
        raise ValueError('Not a registry hive')
    if any(uuid.UUID(x).int == 0 for x in (disk_guid, esp_guid, windows_guid)):
        raise ValueError('Zero GUID is not a boot target')
    result = template
    for old_part, new_part, count in ((PLACEHOLDER_ESP, esp_guid, 1),
                                      (PLACEHOLDER_WINDOWS, windows_guid, 2)):
        old = device_blob(PLACEHOLDER_DISK, old_part)
        if result.count(old) != count:
            raise ValueError('Unexpected BCD device-record count')
        result = result.replace(old, device_blob(disk_guid, new_part))
    if len(result) != len(template) or result[:4096] != template[:4096]:
        raise ValueError('BCD edit changed hive layout/header')
    return result
