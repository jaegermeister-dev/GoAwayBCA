const std=@import("std");
const parser=@import("boot_store_parse.zig");
const check=@import("boot_store_identity.zig");
fn exercise(data: []const u8, windows: [16]u8) !void {
    const hive=try std.testing.allocator.create(parser.Hive);
    defer std.testing.allocator.destroy(hive);
    try hive.initInto(data);
    var id: check.Identity=.{.esp_disk=.{0x0e,0xf0,0x60,0x7c,0x3f,0x22,0x63,0x41,0x9f,0xd2,0x6e,0xe6,0x3d,0x85,0x03,0xac},.esp=.{0x4f,0x0b,0x44,0x5a,0x1b,0x5c,0xf2,0x48,0x9d,0x6d,0xa7,0xc7,0x04,0x30,0xf3,0xf1},.windows_disk=.{0x0e,0xf0,0x60,0x7c,0x3f,0x22,0x63,0x41,0x9f,0xd2,0x6e,0xe6,0x3d,0x85,0x03,0xac},.windows=windows};
    try check.validate(hive,&id);
    id.windows[0]^=1;
    try std.testing.expectError(error.ForeignWindowsVolume,check.validate(hive,&id));
}
test "serviced Windows 7 with other OS firmware entries is accepted without changing its Windows target" {
    try exercise(@embedFile("BCD7-firmware-mirror.test"),.{0xfe,0x78,0xf7,0x8a,0x56,0x48,0xe7,0x45,0xad,0x4c,0xd0,0x0a,0x40,0x99,0x79,0x88});
}
